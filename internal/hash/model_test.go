// chiSquareCrit63 is the χ² critical value for 63 degrees of freedom at
// p = 0.001: a uniform hash over 64 lanes exceeds it once in a thousand
// samples.
const chiSquareCrit63 = 103.4

// TestModel checks the contract of every kind: determinism, agreement of
// the byte and string entry points, output width, seed sensitivity,
// known answers from the upstream implementations, lane distribution
// (χ² over 64 lanes for 1e6 keys of every corpus) and 64-bit collisions
// over 1e7 distinct keys.
func TestModel(t *testing.T) {
	for _, k := range Kinds() {
		t.Run(k.String(), func(t *testing.T) {
			t.Parallel()
			t.Run("deterministic", func(t *testing.T) { modelDeterministic(t, k) })
			t.Run("bytes-string-agree", func(t *testing.T) { modelBytesString(t, k) })
			t.Run("width", func(t *testing.T) { modelWidth(t, k) })
			t.Run("seed", func(t *testing.T) { modelSeed(t, k) })
			t.Run("kat", func(t *testing.T) { modelKAT(t, k) })
			t.Run("chi-square", func(t *testing.T) { modelChiSquare(t, k) })
			t.Run("collisions", func(t *testing.T) { modelCollisions(t, k) })
		})
	}
}

// modelLengths are the input sizes the contract subtests sweep: every tail
// length of every kind plus the XXH3 block boundaries.
func modelLengths() []int {
	ls := make([]int, 0, 320)
	for n := range 300 {
		ls = append(ls, n)
	}
	return append(ls, 403, 512, 1000, 1024, 1025, 1088, 2048, 2049, 2099, 2240, 2367, 4096)
}

var modelSeeds = []uint64{0, 1, KafkaSeed, 0x0123456789abcdef, 1 << 32, ^uint64(0)}

func modelDeterministic(t *testing.T, k Kind) {
	h := mustNew(t, k)
	r := rand.New(rand.NewPCG(3, 4))
	for _, n := range modelLengths() {
		a := make([]byte, n)
		for i := range a {
			a[i] = byte(r.Uint32())
		}
		b := slices.Clone(a)
		for _, seed := range modelSeeds {
			x, y, z := h.Bytes(seed, a), h.Bytes(seed, b), h.Bytes(seed, a)
			if x != y || x != z {
				t.Fatalf("len %d seed %#x: %#x %#x %#x", n, seed, x, y, z)
			}
		}
	}
}

// modelBytesString feeds identical content through both entry points at
// every offset within a word, so unaligned reads and every tail path are
// covered.
func modelBytesString(t *testing.T, k Kind) {
	h := mustNew(t, k)
	r := rand.New(rand.NewPCG(5, 6))
	backing := make([]byte, 4096+16)
	for i := range backing {
		backing[i] = byte(r.Uint32())
	}
	for _, n := range modelLengths() {
		for off := range 8 {
			key := backing[off : off+n]
			s := string(key)
			for _, seed := range modelSeeds {
				if x, y := h.Bytes(seed, key), h.String(seed, s); x != y {
					t.Fatalf("len %d off %d seed %#x: Bytes %#x != String %#x", n, off, seed, x, y)
				}
			}
		}
	}
}

// modelWidth checks Bits: every value is below 1<<Bits and a 64-bit kind
// really uses its high word.
func modelWidth(t *testing.T, k Kind) {
	h := mustNew(t, k)
	r := rand.New(rand.NewPCG(7, 8))
	highUsed := 0
	const n = 10000
	var buf [16]byte
	for range n {
		binary.LittleEndian.PutUint64(buf[:], r.Uint64())
		binary.LittleEndian.PutUint64(buf[8:], r.Uint64())
		v := h.Bytes(0, buf[:])
		if k.Bits() < 64 && v>>k.Bits() != 0 {
			t.Fatalf("value %#x exceeds %d bits", v, k.Bits())
		}
		if v>>32 != 0 {
			highUsed++
		}
	}
	if k.Bits() == 64 && highUsed < n*9/10 {
		t.Fatalf("only %d of %d values use the high word", highUsed, n)
	}
	if k.Bits() == 32 && highUsed != 0 {
		t.Fatalf("%d values exceed 32 bits", highUsed)
	}
}

// modelSeed: different seeds give different values for (almost) every key,
// including seeds that differ only in the high word.
func modelSeed(t *testing.T, k Kind) {
	h := mustNew(t, k)
	r := rand.New(rand.NewPCG(9, 10))
	pairs := [][2]uint64{{0, 1}, {1, 1 << 32}, {KafkaSeed, KafkaSeed + 1}, {0, ^uint64(0)}}
	for _, p := range pairs {
		equal := 0
		const n = 10000
		var buf [24]byte
		for i := range n {
			binary.LittleEndian.PutUint64(buf[:], uint64(i))
			binary.LittleEndian.PutUint64(buf[8:], r.Uint64())
			key := buf[:8+i%17]
			if h.Bytes(p[0], key) == h.Bytes(p[1], key) {
				equal++
			}
		}
		// A 32-bit output collides once per 2^32 pairs; anything above two
		// out of 10 000 is a seed that does not reach the state.
		if equal > 2 {
			t.Fatalf("seeds %#x and %#x agree on %d of %d keys", p[0], p[1], equal, n)
		}
	}
}

// modelKAT compares against the upstream implementations: hash/fnv for
// FNV-1a at seed 0, the tables generated by wyhash.h 4.3, xxHash 0.8.3 and
// Kafka's Utils.murmur2 (testdata/kat), and an independent MurmurHash2
// port for the seeded Murmur2 form.
func modelKAT(t *testing.T, k Kind) {
	h := mustNew(t, k)
	buf := katBuffer()
	switch k {
	case FNV1a:
		for _, n := range modelLengths() {
			std := fnv.New64a()
			_, _ = std.Write(buf[:n])
			if got, want := h.Bytes(0, buf[:n]), std.Sum64(); got != want {
				t.Fatalf("len %d: %#x, hash/fnv %#x", n, got, want)
			}
		}
	case Wyhash:
		vectors := []string{
			"", "a", "abc", "message digest", "abcdefghijklmnopqrstuvwxyz",
			"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789",
			"12345678901234567890123456789012345678901234567890123456789012345678901234567890",
		}
		n := 0
		for _, f := range katRows(t, "wyhash.txt") {
			switch f[0] {
			case "V":
				i, _ := strconv.Atoi(f[1])
				want, _ := strconv.ParseUint(f[2], 16, 64)
				if got := h.String(uint64(i), vectors[i]); got != want {
					t.Fatalf("test_vector %d %q: %#x, upstream %#x", i, vectors[i], got, want)
				}
			case "K":
				checkKATRow(t, h, buf, f)
			}
			n++
		}
		if n < 500 {
			t.Fatalf("only %d rows", n)
		}
	case XXH3:
		n := 0
		for _, f := range katRows(t, "xxh3.txt") {
			checkKATRow(t, h, buf, f)
			n++
		}
		if n < 500 {
			t.Fatalf("only %d rows", n)
		}
		if got := h.Bytes(0, nil); got != 0x2D06800538D394C2 {
			t.Fatalf("XXH3_64bits(\"\") = %#x", got)
		}
	case Murmur2:
		// Kafka's tables are covered by TestKafka; the seeded form is
		// checked against an independent port at every length and every
		// 32-bit seed (the contract: seeds below 1<<32 are MurmurHash2's).
		for _, n := range modelLengths() {
			for _, seed := range modelSeeds {
				if seed>>32 != 0 {
					continue
				}
				want := uint64(murmur2Ref(uint32(seed), buf[:n]))
				if got := h.Bytes(seed, buf[:n]); got != want {
					t.Fatalf("len %d seed %#x: %#x, reference %#x", n, seed, got, want)
				}
			}
		}
		if got := h.Bytes(KafkaSeed, []byte("foobar")); int32(uint32(got)) != -790332482 {
			t.Fatalf("murmur2(foobar) = %d, Kafka says -790332482", int32(uint32(got)))
		}
	case Maphash:
		t.Skip("maphash is seeded per process (Stable() = false): no cross-process known answers exist; TestStable covers the instability")
	default:
		t.Fatalf("no known answers for %v", k)
	}
}

// checkKATRow checks one "K <len> <seed> <hash>" row.
func checkKATRow(t *testing.T, h Hash, buf []byte, f []string) {
	t.Helper()
	if len(f) != 4 {
		t.Fatalf("malformed row %q", f)
	}
	n, _ := strconv.Atoi(f[1])
	seed, err := strconv.ParseUint(f[2], 16, 64)
	if err != nil {
		t.Fatal(err)
	}
	want, err := strconv.ParseUint(f[3], 16, 64)
	if err != nil {
		t.Fatal(err)
	}
	if got := h.Bytes(seed, buf[:n]); got != want {
		t.Fatalf("len %d seed %#x: %#x, upstream %#x", n, seed, got, want)
	}
	if got := h.String(seed, string(buf[:n])); got != want {
		t.Fatalf("len %d seed %#x: String %#x, upstream %#x", n, seed, got, want)
	}
}

// murmur2Ref is an independent port of Kafka's Utils.murmur2 generalised
// to a 32-bit caller seed (Java int arithmetic on uint32).
func murmur2Ref(seed uint32, data []byte) uint32 {
	const m = 0x5bd1e995
	length := len(data)
	h := seed ^ uint32(length)
	length4 := length / 4
	for i := range length4 {
		i4 := i * 4
		k := uint32(data[i4]) | uint32(data[i4+1])<<8 | uint32(data[i4+2])<<16 | uint32(data[i4+3])<<24
		k *= m
		k ^= k >> 24
		k *= m
		h *= m
		h ^= k
	}
	switch length % 4 {
	case 3:
		h ^= uint32(data[(length&^3)+2]) << 16
		fallthrough
	case 2:
		h ^= uint32(data[(length&^3)+1]) << 8
		fallthrough
	case 1:
		h ^= uint32(data[length&^3])
		h *= m
	}
	h ^= h >> 13
	h *= m
	h ^= h >> 15
	return h
}

// corpus is one million distinct keys of one shape, laid out contiguously.
type corpus struct {
	name string
	data []byte
	off  []int32 // len(off) == keys+1
}

func (c *corpus) key(i int) []byte { return c.data[c.off[i]:c.off[i+1]] }

func (c *corpus) keys() int { return len(c.off) - 1 }

const corpusKeys = 1000000

// corpusSpecs are the real-world key shapes sequential decimal ids, binary counters, UUIDs, random binary
// keys, zero-padded ids and hierarchical paths.
var corpusSpecs = []struct {
	name string
	gen  func(i int, r *rand.Rand, dst []byte) []byte
}{
	{"seq-decimal", func(i int, _ *rand.Rand, dst []byte) []byte {
		return strconv.AppendInt(append(dst, "order-"...), int64(i), 10)
	}},
	{"seq-be64", func(i int, _ *rand.Rand, dst []byte) []byte {
		return binary.BigEndian.AppendUint64(dst, uint64(i))
	}},
	{"seq-le32", func(i int, _ *rand.Rand, dst []byte) []byte {
		return binary.LittleEndian.AppendUint32(dst, uint32(i))
	}},
	{"uuid", func(_ int, r *rand.Rand, dst []byte) []byte {
		var u [16]byte
		binary.LittleEndian.PutUint64(u[:], r.Uint64())
		binary.LittleEndian.PutUint64(u[8:], r.Uint64())
		u[6] = u[6]&0x0f | 0x40
		u[8] = u[8]&0x3f | 0x80
		const hexdigits = "0123456789abcdef"
		for i, b := range u {
			if i == 4 || i == 6 || i == 8 || i == 10 {
				dst = append(dst, '-')
			}
			dst = append(dst, hexdigits[b>>4], hexdigits[b&15])
		}
		return dst
	}},
	{"random-16", func(_ int, r *rand.Rand, dst []byte) []byte {
		dst = binary.LittleEndian.AppendUint64(dst, r.Uint64())
		return binary.LittleEndian.AppendUint64(dst, r.Uint64())
	}},
	{"padded-12", func(i int, _ *rand.Rand, dst []byte) []byte {
		s := strconv.Itoa(i)
		for range 12 - len(s) {
			dst = append(dst, '0')
		}
		return append(dst, s...)
	}},
	{"path", func(i int, _ *rand.Rand, dst []byte) []byte {
		dst = strconv.AppendInt(append(dst, "tenant-"...), int64(i%1000), 10)
		dst = strconv.AppendInt(append(dst, "/user-"...), int64(i/1000), 10)
		return strconv.AppendInt(append(dst, "/evt-"...), int64(i), 10)
	}},
}

var (
	corporaOnce sync.Once
	corpora     []*corpus
)

// loadCorpora builds every corpus once per test binary; kinds share them.
func loadCorpora() []*corpus {
	corporaOnce.Do(func() {
		for _, spec := range corpusSpecs {
			r := rand.New(rand.NewPCG(11, 12))
			c := &corpus{name: spec.name, off: make([]int32, 1, corpusKeys+1)}
			c.data = make([]byte, 0, 40*corpusKeys)
			for i := range corpusKeys {
				c.data = spec.gen(i, r, c.data)
				c.off = append(c.off, int32(len(c.data)))
			}
			corpora = append(corpora, c)
		}
	})
	return corpora
}

// chiSquare returns Σ (observed − expected)² / expected for total samples
// spread over len(counts) lanes.
func chiSquare(counts []int, total int) float64 {
	expected := float64(total) / float64(len(counts))
	x := 0.0
	for _, c := range counts {
		d := float64(c) - expected
		x += d * d / expected
	}
	return x
}

// laneChiSquare hashes every key of c with seed into 64 lanes.
func laneChiSquare(h Hash, seed uint64, c *corpus) float64 {
	var counts [64]int
	for i := range c.keys() {
		counts[Lane(h.Bytes(seed, c.key(i)), 64)]++
	}
	return chiSquare(counts[:], c.keys())
}

// modelChiSquare: 64 lanes, 1e6 keys per corpus, χ² < 103.4 (p = 0.001 at
// 63 degrees of freedom) for two seeds. An unstable kind draws a fresh
// runtime seed per process, so one sample would fail spuriously once in a
// thousand runs; it gets a second independent sample before failing.
func modelChiSquare(t *testing.T, k Kind) {
	h := mustNew(t, k)
	for _, c := range loadCorpora() {
		t.Run(c.name, func(t *testing.T) {
			for _, seed := range []uint64{0, 0x5eed} {
				x := laneChiSquare(h, seed, c)
				if x >= chiSquareCrit63 && !k.Stable() {
					y := laneChiSquare(h, seed^0xa5a5a5a5, c)
					t.Logf("seed %#x: χ² = %.1f, second sample %.1f", seed, x, y)
					x = min(x, y)
				}
				if x >= chiSquareCrit63 {
					t.Fatalf("seed %#x: χ² = %.1f over 64 lanes and %d keys (limit %.1f)", seed, x, c.keys(), chiSquareCrit63)
				}
				t.Logf("seed %#x: χ² = %.1f", seed, x)
			}
		})
	}
}

// collisionKeys is the number of distinct keys hashed by the collision
// test: 1e7 by default, 1e6 under -short, or IQMQ_HASH_COLLISION_KEYS.
func collisionKeys(t *testing.T) int {
	if v := os.Getenv("IQMQ_HASH_COLLISION_KEYS"); v != "" {
		n, err := strconv.Atoi(v)
		if err != nil || n < 1000 {
			t.Fatalf("IQMQ_HASH_COLLISION_KEYS=%q", v)
		}
		return n
	}
	if testing.Short() {
		return 1000000
	}
	return 10000000
}

// modelCollisions hashes distinct 16-byte keys (counter + random word) and
// counts equal values. A 64-bit kind must not collide at all (expected
// 2.7e-6 collisions for 1e7 keys); a 32-bit kind must collide like a random
// function: n(n−1)/2 / 2^32, within ±25 %.
func modelCollisions(t *testing.T, k Kind) {
	n := collisionKeys(t)
	h := mustNew(t, k)
	r := rand.New(rand.NewPCG(13, 14))
	hashes := make([]uint64, n)
	var buf [16]byte
	for i := range n {
		binary.LittleEndian.PutUint64(buf[:], uint64(i))
		binary.LittleEndian.PutUint64(buf[8:], r.Uint64())
		hashes[i] = h.Bytes(0, buf[:])
	}
	slices.Sort(hashes)
	collisions := 0
	for i := 1; i < n; i++ {
		if hashes[i] == hashes[i-1] {
			collisions++
		}
	}
	expected := float64(n) * float64(n-1) / 2 / math.Ldexp(1, k.Bits())
	t.Logf("%d keys: %d collisions (expected %.2f for a random %d-bit function)", n, collisions, expected, k.Bits())
	switch {
	case k.Bits() == 64 && collisions != 0:
		t.Fatalf("%d collisions among %d keys", collisions, n)
	case k.Bits() < 64 && (float64(collisions) < 0.75*expected || float64(collisions) > 1.25*expected):
		t.Fatalf("%d collisions among %d keys, expected about %.0f", collisions, n, expected)
	}
}
