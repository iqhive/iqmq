// Package fusegen writes the generated fused middleware compositions.
//
// The fused kind trades one generated type per chain length for the chain of
// separately allocated closures the reference composition builds: the
// middleware functions and the continuations that bind them sit in one
// object, so a call walks one struct instead of a linked list of closures.
// Everything longer than the generated arities falls back to the closure
// composition, which is why the generator only has to cover the lengths a
// real runner uses.
//
// The output is checked against the committed file by a test in mwchain, so
// the file and this generator cannot drift apart.
package fusegen

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"
)

// Max is the longest chain the generated compositions cover.
const Max = 8

// Source returns the content of mwchain's fused_gen.go for chain lengths up
// to max, or fails when the generated text does not parse.
func Source(max int) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/fusegen; DO NOT EDIT.\n\n")
	b.WriteString("package mwchain\n\n")
	b.WriteString("import \"context\"\n\n")
	b.WriteString("// MaxFused is the longest chain the generated compositions cover. A\n")
	b.WriteString("// longer chain falls back to the closure composition.\n")
	fmt.Fprintf(&b, "const MaxFused = %d\n\n", max)
	b.WriteString("// newFusedChain returns the generated composition of fns around h.\n")
	b.WriteString("// A chain longer than MaxFused falls back to the closure composition.\n")
	b.WriteString("func newFusedChain[D any](h Handler[D], fns []Func[D]) Chain[D] {\n")
	b.WriteString("\tswitch len(fns) {\n")
	for n := range max + 1 {
		fmt.Fprintf(&b, "\tcase %d:\n\t\treturn newFused%d(h, fns)\n", n, n)
	}
	b.WriteString("\tdefault:\n\t\treturn newClosureChain(h, fns)\n\t}\n}\n")
	for n := range max + 1 {
		writeArity(&b, n)
	}
	// The struct fields are laid out by the formatter rather than by hand,
	// so the committed file is exactly what gofmt would produce and the
	// up-to-date test in mwchain can compare it byte for byte.
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("fusegen: generated source does not parse: %w", err)
	}
	return src, nil
}

// writeArity writes the type, constructor and methods for a chain of n
// middlewares.
func writeArity(b *bytes.Buffer, n int) {
	fmt.Fprintf(b, "\n// fused%d is the composition of %s around a handler.\n", n, links(n))
	fmt.Fprintf(b, "type fused%d[D any] struct {\n", n)
	if n > 0 {
		fmt.Fprintf(b, "\t%s Func[D]\n", fields("m", n))
	}
	b.WriteString("\th Handler[D]\n")
	if n > 1 {
		fmt.Fprintf(b, "\t%s Handler[D]\n", fields("n", n-1))
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(b, "func newFused%d[D any](h Handler[D], fns []Func[D]) *fused%d[D] {\n", n, n)
	fmt.Fprintf(b, "\tc := &fused%d[D]{", n)
	for i := range n {
		fmt.Fprintf(b, "m%d: fns[%d], ", i, i)
	}
	b.WriteString("h: h}\n")
	// The continuations are bound once, here, so that a call allocates
	// nothing: the innermost one ends at the handler, and each outer one
	// hands the next middleware the continuation below it.
	for i := n - 2; i >= 0; i-- {
		next := "c.n" + strconv.Itoa(i+1)
		if i == n-2 {
			next = "c.h"
		}
		fmt.Fprintf(b, "\tc.n%d = func(ctx context.Context, d D) error { return c.m%d(ctx, d, %s) }\n", i, i+1, next)
	}
	b.WriteString("\treturn c\n}\n\n")

	fmt.Fprintf(b, "// Handle implements Chain.\nfunc (c *fused%d[D]) Handle(ctx context.Context, d D) error {\n", n)
	switch n {
	case 0:
		b.WriteString("\treturn c.h(ctx, d)\n")
	case 1:
		b.WriteString("\treturn c.m0(ctx, d, c.h)\n")
	default:
		b.WriteString("\treturn c.m0(ctx, d, c.n0)\n")
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(b, "// Len implements Chain.\nfunc (c *fused%d[D]) Len() int { return %d }\n\n", n, n)
	fmt.Fprintf(b, "// Kind implements Chain.\nfunc (c *fused%d[D]) Kind() Kind { return Fused }\n", n)
}

// fields renders "p0, p1, …, p(n-1)".
func fields(prefix string, n int) string {
	parts := make([]string, n)
	for i := range n {
		parts[i] = prefix + strconv.Itoa(i)
	}
	return strings.Join(parts, ", ")
}

// links renders the English for a middleware count.
func links(n int) string {
	switch n {
	case 0:
		return "no middleware"
	case 1:
		return "one middleware"
	default:
		return strconv.Itoa(n) + " middlewares"
	}
}
