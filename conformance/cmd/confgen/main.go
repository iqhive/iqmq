// Command confgen turns conformance reports into the generated capability
// artefacts: capabilities.json, docs/drivers/matrix.md, per-driver capability
// includes and the README matrix block.
//
//	confgen -reports conformance/reports/latest -root. [-check]
//	confgen -reports conformance/reports/latest -incoming <dir> -root.
//
// With -check the outputs are rendered in memory and compared with the files
// on disk; any difference is a failure (the CI "generated" job). With
// -incoming the nightly's freshly downloaded reports are ATTESTED and merged
// into the report directory before generation, which is the step the
// integration workflow used to perform with `cp -f … || true`: a download
// that produced nothing was swallowed, generation regenerated the committed
// reports, the diff was empty and the job reported success having refreshed
// nothing.
//
// # What is refused
//
// A capability matrix is a claim about software versions, so a report that
// cannot support one is refused rather than published:
//
//   - a report no suite in the conformance suites manifest produces, and a suite whose
//     report is missing — the matrix's columns and CI's jobs are the same set;
//   - a report whose commit is not a commit, or that names no Go toolchain,
//     or whose date is in the future;
//   - a report from a broker image conformance/harness/images.lock does not
//     pin, or one naming a digest the lock pins differently;
//   - a report far older than the newest in the same corpus, because a matrix
//     built from reports months apart is not one claim;
//   - a report recording a FAILED scenario.
package main

