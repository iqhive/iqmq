// GeneratedMarker opens every per-driver page this command writes. It is what
// lets the command recognise -- and delete -- a page it wrote for a driver
// whose report has since gone away; a page nothing regenerates is never
// compared with anything and drifts in silence.
const GeneratedMarker = "<!-- generated by confgen"

// defaults for the two time bounds. Both are deliberately generous: they are
// here to catch a corpus nobody refreshed, not to expire evidence.
const (
	// DefaultMaxStale bounds how far behind the NEWEST report in a corpus
	// any other report may be. It is relative rather than absolute so that
	// it cannot rot with the wall clock: a corpus refreshed together stays
	// green for ever, and a corpus in which one suite is left months
	// behind does not.
	DefaultMaxStale = 60 * 24 * time.Hour
	// DefaultMaxIncomingAge bounds how old a report a NIGHTLY delivers may
	// be, against the wall clock. The nightly runs daily.
	DefaultMaxIncomingAge = 7 * 24 * time.Hour
	// clockSkew is how far into the future a report's date may be before
	// it is read as wrong rather than as a runner's clock.
	clockSkew = 2 * time.Hour
)

// IncomingMode is the run mode the nightly's download comes from: the
// integration workflow's `conformance` job drives `tools/suites -mode
// integration`, so every suite declaring that mode owes the aggregate step a
// report and a suite that declares only `inprocess` (the memory driver) does
// not.
const IncomingMode = "integration"

type options struct {
	reports  string
	incoming string
	root     string
	check    bool
	mode     string
	maxStale time.Duration
	maxAge   time.Duration
	now      time.Time
}

func main() {
	var opt options
	flag.StringVar(&opt.reports, "reports", "conformance/reports/latest", "directory of conformance reports")
	flag.StringVar(&opt.incoming, "incoming", "", "directory of freshly delivered reports to attest and merge before generating")
	flag.StringVar(&opt.root, "root", ".", "repository root")
	flag.BoolVar(&opt.check, "check", false, "verify generated files are up to date instead of writing them")
	flag.StringVar(&opt.mode, "expect-mode", IncomingMode, "the run mode -incoming is a delivery of; every suite declaring it owes a report")
	flag.DurationVar(&opt.maxStale, "max-stale", DefaultMaxStale, "how far behind the newest report in the corpus another may be")
	flag.DurationVar(&opt.maxAge, "max-incoming-age", DefaultMaxIncomingAge, "how old a report -incoming delivers may be")
	nowFlag := flag.String("now", "", "RFC 3339 instant to read as now (tests; default the clock)")
	flag.Parse()
	opt.now = time.Now().UTC()
	if *nowFlag != "" {
		t, err := time.Parse(time.RFC3339, *nowFlag)
		if err != nil {
			fmt.Fprintln(os.Stderr, "confgen: -now:", err)
			os.Exit(1)
		}
		opt.now = t.UTC()
	}
	if err := run(opt); err != nil {
		fmt.Fprintln(os.Stderr, "confgen:", err)
		os.Exit(1)
	}
}

func run(opt options) error {
	suites, err := loadSuites(opt.root)
	if err != nil {
		return err
	}
	lock, err := loadImageLock(opt.root)
	if err != nil {
		return err
	}
	if opt.incoming != "" {
		delivered, err := deliver(opt, suites)
		if err != nil {
			return err
		}
		fmt.Fprintf(os.Stderr, "confgen: %d report(s) delivered into %s\n", delivered, opt.reports)
	}
	rs, err := report.LoadDir(opt.reports)
	if ((err == nil && len(rs) == 0) || errors.Is(err, os.ErrNotExist)) && opt.check && opt.incoming == "" {
		generated, _ := filepath.Glob(filepath.Join(opt.root, "docs/drivers/*.capabilities.md"))
		for _, name := range []string{"capabilities.json", "docs/drivers/matrix.md"} {
			if _, statErr := os.Stat(filepath.Join(opt.root, name)); statErr == nil {
				generated = append(generated, name)
			}
		}
		if len(generated) != 0 {
			return fmt.Errorf("generated capability claims exist without source reports: %v", generated)
		}
		fmt.Fprintln(os.Stderr, "confgen: no reports or generated capability claims to check")
		return nil
	}
	if err != nil {
		return err
	}
	if errs := attest(rs, suites, lock, opt); len(errs) > 0 {
		return problems(errs)
	}
	entries := make([]entry, 0, len(rs))
	for _, r := range rs {
		entries = append(entries, newEntry(r))
	}
	outputs, err := render(entries, opt.root)
	if err != nil {
		return err
	}
	drift, err := reconcile(outputs, opt)
	if err != nil {
		return err
	}
	if len(drift) > 0 {
		sort.Strings(drift)
		return fmt.Errorf("generated files are stale: %s", strings.Join(drift, ", "))
	}
	fmt.Fprintf(os.Stderr, "confgen: %d report(s), %d file(s) %s\n", len(rs), len(outputs),
		map[bool]string{true: "checked", false: "written"}[opt.check])
	return nil
}

// problems folds one error per defect into one message, so a wrong corpus is
// reported whole rather than one line per run.
func problems(errs []error) error {
	sort.Slice(errs, func(i, j int) bool { return errs[i].Error() < errs[j].Error() })
	var b strings.Builder
	fmt.Fprintf(&b, "%d problem(s) in the conformance evidence:", len(errs))
	for _, err := range errs {
		b.WriteString("\n  - " + err.Error())
	}
	return errors.New(b.String())
}

// ---------------------------------------------------------------- the suites

// suiteManifest is the part of the conformance suites manifest this command needs.
//
// tools/suites owns the schema and `make suites-check` holds every field of
// every entry to the repository. This reader deliberately does NOT reject
// unknown fields: a field added there must not stop the capability artefacts
// being generated.
type suiteManifest struct {
	Schema int     `json:"schema"`
	Suites []suite `json:"suites"`
}

type suite struct {
	Name       string   `json:"name"`
	Driver     string   `json:"driver"`
	Reports    []string `json:"reports"`
	CrossCheck bool     `json:"cross_check"`
	// Image is the name conformance/harness/images.lock gives the broker
	// this suite runs against. `make suites-check` holds every entry to
	// having one; this command holds the REPORT to it, so a report filed
	// under a suite whose broker it was not made against is refused.
	Image    string   `json:"image"`
	Evidence string   `json:"evidence"`
	Runs     []string `json:"runs"`
}

// SuitesPath is the conformance suites manifest's path from the repository root.
const SuitesPath = "conformance/suites.json"

// ImageLockPath is conformance/harness/images.lock's path from the root.
const ImageLockPath = "conformance/harness/images.lock"

func loadSuites(root string) (*suiteManifest, error) {
	path := filepath.Join(root, SuitesPath)
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("the suite list says which run produces each report and it cannot be read: %w", err)
	}
	var m suiteManifest
	if err := json.Unmarshal(data, &m); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if m.Schema != 1 {
		return nil, fmt.Errorf("%s: schema is %d, want 1", path, m.Schema)
	}
	if len(m.Suites) == 0 {
		return nil, fmt.Errorf("%s lists no suite, so no report has a provenance", path)
	}
	return &m, nil
}

// producer returns the suite that PUBLISHES a report of that file name. A
// cross-check names a report it does not publish -- it exists to be compared
// with another suite's -- so it is never the answer.
func (m *suiteManifest) producer(file string) (suite, bool) {
	for _, s := range m.Suites {
		if s.CrossCheck {
			continue
		}
		for _, r := range s.Reports {
			if r == file {
				return s, true
			}
		}
	}
	return suite{}, false
}

// expected is every report a non-cross-check suite publishes. With a mode it
// is narrowed to the suites that declare it, which is what a delivery of one
// run mode owes.
func (m *suiteManifest) expected(mode string) []string {
	var out []string
	for _, s := range m.Suites {
		if s.CrossCheck {
			continue
		}
		if mode != "" && !has(s.Runs, mode) {
			continue
		}
		out = append(out, s.Reports...)
	}
	sort.Strings(out)
	return out
}

func has(hay []string, needle string) bool {
	for _, s := range hay {
		if s == needle {
			return true
		}
	}
	return false
}

// ------------------------------------------------------------ the image lock

// imageLock is conformance/harness/images.lock, written by
// hack/images-lock.sh: one `name repository@sha256:…` line per broker image.
//
// Nothing read this file before this command did. It was a record of what the
// tags resolved to on the day it was written (the maintenance notes's standing
// item, owner /); it is now also what a capability claim's broker has to
// be one of.
type imageLock struct {
	digest map[string]string // repository -> sha256:…
	names  map[string]string // images.lock name -> repository
}

func loadImageLock(root string) (imageLock, error) {
	path := filepath.Join(root, ImageLockPath)
	data, err := os.ReadFile(path)
	if err != nil {
		return imageLock{}, fmt.Errorf("the image lock is what a report's broker is checked against and it cannot be read: %w", err)
	}
	l := imageLock{digest: map[string]string{}, names: map[string]string{}}
	for i, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) != 2 {
			return imageLock{}, fmt.Errorf("%s:%d: %q is not `name repository@digest`", path, i+1, line)
		}
		repo, dig, ok := strings.Cut(fields[1], "@")
		if !ok || !strings.HasPrefix(dig, "sha256:") {
			return imageLock{}, fmt.Errorf("%s:%d: %q names no digest", path, i+1, fields[1])
		}
		l.digest[repo] = dig
		l.names[fields[0]] = repo
	}
	if len(l.digest) == 0 {
		return imageLock{}, fmt.Errorf("%s pins no image", path)
	}
	return l, nil
}

// splitImage separates an image reference into its repository and the digest
// it names, if it names one. A tag is not a digest and is dropped: the colon
// that introduces it is the last one after the last slash, which is what keeps
// a registry port from being read as a tag.
func splitImage(image string) (repo, digest string) {
	if repo, dig, ok := strings.Cut(image, "@"); ok {
		return repo, dig
	}
	slash := strings.LastIndexByte(image, '/')
	if colon := strings.LastIndexByte(image, ':'); colon > slash {
		return image[:colon], ""
	}
	return image, ""
}

// pinned reports whether the lock pins this image's repository, and whether a
// digest the reference names is the one the lock pins.
func (l imageLock) pinned(image string) error {
	repo, digest := splitImage(image)
	want, ok := l.digest[repo]
	if !ok {
		names := make([]string, 0, len(l.names))
		for n := range l.names {
			names = append(names, n)
		}
		sort.Strings(names)
		return fmt.Errorf("the broker image %q is not one %s pins (it pins %s)", image, ImageLockPath, strings.Join(names, ", "))
	}
	if digest != "" && digest != want {
		return fmt.Errorf("the broker image %q names a digest %s pins differently (%s)", image, ImageLockPath, want)
	}
	return nil
}

// ------------------------------------------------------------- the attestation

// attest holds a corpus of reports to what a capability matrix needs of it and
// returns one error per defect.
//
// It is the check the whole increment is about. `make generate` used to accept
// anything report.Parse accepted, so a report dated 1999 with no commit, no Go
// version and a broker image that exists nowhere in this repository was
// published into the matrix and the command exited 0.
func attest(rs []*report.Report, m *suiteManifest, lock imageLock, opt options) []error {
	var errs []error
	fail := func(format string, args ...any) { errs = append(errs, fmt.Errorf(format, args...)) }
	if len(rs) == 0 {
		return []error{fmt.Errorf("%s holds no conformance report, so there is no evidence to generate from", opt.reports)}
	}
	var newest time.Time
	dates := make(map[string]time.Time, len(rs))
	for _, r := range rs {
		t, err := time.Parse(time.RFC3339, r.Date)
		if err != nil {
			fail("%s: %v", r.FileName(), err)
			continue
		}
		dates[r.FileName()] = t
		if t.After(newest) {
			newest = t
		}
	}
	present := map[string]bool{}
	for _, r := range rs {
		file := r.FileName()
		present[file] = true
		where := file
		s, ok := m.producer(file)
		if !ok {
			fail("%s: no suite in %s publishes it, so the matrix would carry a column whose provenance nothing states", where, SuitesPath)
		} else if string(r.Evidence) != s.Evidence {
			fail("%s: suite %q declares %q evidence and the report was made with %q", where, s.Name, s.Evidence, r.Evidence)
		}
		if !isCommit(r.Commit) {
			fail("%s: %q is not a commit; a capability claim has to name the tree that produced it", where, r.Commit)
		}
		if !strings.HasPrefix(r.Go, "go1.") {
			fail("%s: %q is not a Go toolchain version", where, r.Go)
		}
		switch r.Evidence {
		case report.EvidenceContainer, report.EvidenceEmulator:
			if err := lock.pinned(r.Broker.Image); err != nil {
				fail("%s: %v", where, err)
			} else if ok && s.Image != "" {
				// Stronger than "an image this repository pins":
				// the image THIS suite's broker is. Without it a
				// Redis report could name the Kafka image and
				// the matrix would carry a Redis column whose
				// version is a different broker's.
				if want := lock.names[s.Image]; want != "" {
					if got, _ := splitImage(r.Broker.Image); got != want {
						fail("%s: suite %q runs against %q (%s) and the report's broker is %q", where, s.Name, s.Image, want, r.Broker.Image)
					}
				}
			}
		case report.EvidenceInProcess:
			if r.Broker.Image == "" {
				fail("%s: an in-process run still has to say what it ran against", where)
			}
		case report.EvidenceManaged:
			// A managed service has no image to pin, which is the
			// reason the specification makes managed its own evidence kind.
		}
		if t, ok := dates[file]; ok {
			if t.After(opt.now.Add(clockSkew)) {
				fail("%s: ran at %s, which is in the future", where, r.Date)
			}
			if age := newest.Sub(t); age > opt.maxStale {
				fail("%s: ran %s before the newest report in this corpus (%s); a matrix built from reports that far apart is not one claim about one tree",
					where, age.Round(time.Hour), opt.maxStale)
			}
		}
		for _, res := range r.Results {
			if res.Outcome == report.Fail {
				fail("%s: the scenario %s FAILED (%s); a driver that does not pass the suite does not publish a capability", where, res.Scenario, res.Note)
			}
		}
		if !hasCapabilityScenarios(r) {
			fail("%s: carries no %s<feature>%s scenario, so the kit that wrote it is not the one this generator reads", where, report.CapabilityPrefix, report.ScenarioClaim)
		}
	}
	for _, want := range m.expected("") {
		if !present[want] {
			fail("%s names the report %s and %s does not hold it; a suite whose report never arrives leaves the matrix silently short of a column", SuitesPath, want, opt.reports)
		}
	}
	return errs
}

// isCommit reports whether s is a git object name: 7 to 40 lower-case hex
// digits. The corpus holds both lengths, and it holds them because two suites
// recorded a short sha.
func isCommit(s string) bool {
	if len(s) < 7 || len(s) > 40 {
		return false
	}
	for _, r := range s {
		if (r < '0' || r > '9') && (r < 'a' || r > 'f') {
			return false
		}
	}
	return true
}

// hasCapabilityScenarios reports whether the report carries the kit's
// per-capability scenarios, which is the contract the rendering reads: the
// `claim` scenario is the one every report has for every feature, and the
// renderer's separation of "advertised" from "verified" depends on being able
// to tell it from a behavioural probe.
func hasCapabilityScenarios(r *report.Report) bool {
	for _, res := range r.Results {
		if _, ok := report.FeatureOfScenario(res.Scenario); ok && strings.HasSuffix(res.Scenario, report.ScenarioClaim) {
			return true
		}
	}
	return false
}

// ------------------------------------------------------------ the delivery

// deliver attests a nightly download and merges it into the report directory.
//
// The integration workflow used to do this with
//
//	cp -f conformance/reports/incoming/*.json conformance/reports/latest/ || true
//	make generate
//
// which cannot fail on stale input. If the download produced nothing the `||
// true` swallowed it, generation regenerated the COMMITTED reports, the diff
// was empty and the job reported success having refreshed nothing -- a nightly
// silently republishing last month's capabilities. Every
// way that can go wrong is an error here: no download at all, a report no
// suite produces, a report that is not newer than the one it replaces, a
// report older than a nightly's own period, and a suite that delivered
// nothing.
func deliver(opt options, m *suiteManifest) (int, error) {
	if fi, err := os.Stat(opt.incoming); err != nil || !fi.IsDir() {
		return 0, fmt.Errorf("the delivery directory %s does not exist, so the run it was meant to carry produced nothing", opt.incoming)
	}
	files, err := filepath.Glob(filepath.Join(opt.incoming, "*.json"))
	if err != nil {
		return 0, err
	}
	if len(files) == 0 {
		return 0, fmt.Errorf("%s holds no report: the download produced nothing, and regenerating from the committed reports would republish them as if they were fresh", opt.incoming)
	}
	sort.Strings(files)
	var errs []error
	fail := func(format string, args ...any) { errs = append(errs, fmt.Errorf(format, args...)) }
	type pending struct {
		src  string
		name string
		data []byte
	}
	var accept []pending
	delivered := map[string]bool{}
	for _, src := range files {
		base := filepath.Base(src)
		data, err := os.ReadFile(src)
		if err != nil {
			fail("%s: %v", base, err)
			continue
		}
		r, err := report.Parse(data)
		if err != nil {
			fail("%s: %v", base, err)
			continue
		}
		name := r.FileName()
		if name != base {
			fail("%s: a run of driver %q profile %q writes %s, so this file is not the report it is named after", base, r.Driver, r.Profile, name)
			continue
		}
		if _, ok := m.producer(name); !ok {
			fail("%s: no suite in %s publishes it; a report from a retired suite is not evidence about this repository", base, SuitesPath)
			continue
		}
		t, err := time.Parse(time.RFC3339, r.Date)
		if err != nil {
			fail("%s: %v", base, err)
			continue
		}
		if age := opt.now.Sub(t); age > opt.maxAge {
			fail("%s: ran %s ago, which is older than a delivery may be (%s); the download carried an old artefact rather than the run that was just made", base, age.Round(time.Hour), opt.maxAge)
			continue
		}
		if cur, err := os.ReadFile(filepath.Join(opt.reports, name)); err == nil {
			if old, err := report.Parse(cur); err == nil && r.Date <= old.Date {
				fail("%s: ran at %s, which is not after the committed report's %s; replacing a report with one that is not newer refreshes nothing", base, r.Date, old.Date)
				continue
			}
		}
		accept = append(accept, pending{src: src, name: name, data: data})
		delivered[name] = true
	}
	for _, want := range m.expected(opt.mode) {
		if !delivered[want] {
			fail("%s declares the %q run and delivered no %s; a suite whose job died leaves the previous night's claim in place looking fresh", SuitesPath, opt.mode, want)
		}
	}
	if len(errs) > 0 {
		return 0, problems(errs)
	}
	if err := os.MkdirAll(opt.reports, 0o750); err != nil {
		return 0, err
	}
	for _, p := range accept {
		if err := os.WriteFile(filepath.Join(opt.reports, p.name), p.data, 0o644); err != nil {
			return 0, err
		}
	}
	return len(accept), nil
}

// --------------------------------------------------------------- the model

type claim struct {
	// Level is the level the driver advertises, or "unread" when no
	// scenario about the claim reached a client to read it.
	Level string `json:"level"`
	// State is what the evidence says: verified, refuted, unrefuted,
	// advertised, unverified, unread or failed. It is the field a consumer of
	// capabilities.json should read, because `verified: false` is four
	// different answers.
	State string `json:"state"`
	// Verified is kept for compatibility with readers of the previous
	// schema: it is true exactly when State is "verified" or "refuted".
	Verified bool   `json:"verified"`
	Evidence string `json:"evidence"`
	// Probed reports whether a behavioural probe produced evidence about
	// the claim in either direction. A claim with Probed false and a
	// Level other than "unsupported" is ADVERTISED AND UNCHECKED, which
	// The specification does not let the matrix present as support.
	Probed bool `json:"probed"`
	// Kind is "guarantee" for a claim about every run rather than about a
	// call: an ordering, a delivery multiplicity, a durability. One run can
	// observe such a claim BROKEN and no run can observe it absent.
	Kind string `json:"kind,omitempty"`
	// Unrefuted marks a denial no run has contradicted, which is not the
	// same unverified state as a claim nobody checked: a driver that
	// truthfully says it does not order messages can never prove it, and
	// the kit used to FAIL it for that.
	Unrefuted bool `json:"unrefuted,omitempty"`
	// Why is the run's own reason for an unverified claim.
	Why string `json:"why,omitempty"`
}

type entry struct {
	Driver       string           `json:"driver"`
	Profile      string           `json:"profile,omitempty"`
	Broker       report.Broker    `json:"broker"`
	Client       report.Client    `json:"client"`
	Go           string           `json:"go"`
	Date         string           `json:"date"`
	Commit       string           `json:"commit,omitempty"`
	CommitStatus string           `json:"commit_status,omitempty"`
	Evidence     string           `json:"evidence"`
	Features     map[string]claim `json:"features"`
}

func newEntry(r *report.Report) entry {
	e := entry{
		Driver: r.Driver, Profile: r.Profile, Broker: r.Broker, Client: r.Client, Go: r.Go,
		Date: r.Date, Commit: r.Commit, CommitStatus: r.CommitStatus, Evidence: string(r.Evidence), Features: map[string]claim{},
	}
	for _, v := range r.Verify() {
		state := v.State()
		c := claim{
			Level:    string(v.Claimed),
			State:    string(state),
			Verified: v.Proven(),
			Evidence: string(r.Evidence),
			Probed:   v.Probed,
		}
		if state != report.StateVerified && state != report.StateRefuted {
			c.Why = v.Note
		}
		if v.Guarantee {
			c.Kind = string(report.KindGuarantee)
			c.Unrefuted = v.Unrefuted()
		}
		e.Features[v.Feature] = c
	}
	return e
}

// name is the column heading and the per-driver page's stem.
func (e *entry) name(sep, closer string) string {
	if e.Profile == "" {
		return e.Driver
	}
	return e.Driver + sep + e.Profile + closer
}

// --------------------------------------------------------------- rendering

// levelGlyph is the five support levels, abbreviated.
var levelGlyph = map[string]string{
	"native": "N", "conditional": "C", "emulated-durable": "ED", "emulated-volatile": "EV", "unsupported": "—",
}

// symbol renders one cell.
//
// Seven states, seven answers. The matrix used to render four of them -- a refusal
// the run observed, a claim the driver advertises that nothing probed, a
// denial nothing could probe, and a failure -- with one em dash, and the
// legend said "unsupported or unverified" as though the difference did not
// matter. It does: eighteen drivers advertise DurableStorage at `native`, and
// a reader of the old matrix concluded that no driver in this repository is
// durable.
func symbol(c claim, present bool) string {
	if !present {
		return "?"
	}
	switch report.State(c.State) {
	case report.StateFailed:
		return "!"
	case report.StateRefuted:
		return "—"
	case report.StateUnrefuted:
		return "·"
	case report.StateUnverified:
		return "?"
	case report.StateUnread:
		// Its own glyph, not "?": "?" says the driver DENIES the claim
		// and nothing proved the denial, and here the run never read
		// what the driver says at all.
		return "∅"
	case report.StateAdvertised:
		return "(" + glyph(c.Level) + ")"
	case report.StateVerified:
		s := glyph(c.Level)
		if c.Evidence == string(report.EvidenceEmulator) {
			s += "◐"
		}
		return s
	}
	return "?"
}

func glyph(level string) string {
	if s := levelGlyph[level]; s != "" {
		return s
	}
	return "?"
}

// Legend is the matrix's key. It is one line per glyph class rather than a
// run-on sentence because six of the ten entries used to be one em dash.
const Legend = "- **N** native · **C** conditional · **ED** emulated durable · **EV** emulated volatile — each VERIFIED by a probe in both directions.\n" +
	"- **(N)** **(C)** **(ED)** **(EV)** — the driver ADVERTISES that level and no probe verified it: a claim without evidence, which the specification does not let this table present as support.\n" +
	"- **—** the driver does not offer it and a probe observed the refusal · **·** a denied guarantee no run contradicted (one run cannot observe an absence) · **?** not offered and nothing established that either · **!** a scenario for the claim FAILED.\n" +
	"- **∅** no scenario for the claim reached a client — the driver documented them as inapplicable or refused the topology they need — so the run never read the level the driver advertises; its page says why.\n" +
	"- **◐** the evidence is an emulator's, never presented as the managed service's.\n"

func renderMatrix(entries []entry) string {
	if len(entries) == 0 {
		return "_No conformance reports yet._\n"
	}
	var b strings.Builder
	b.WriteString("| Capability |")
	for i := range entries {
		b.WriteString(" " + entries[i].name(" (", ")") + " |")
	}
	b.WriteString("\n|---|")
	for range entries {
		b.WriteString("---|")
	}
	b.WriteString("\n")
	for _, f := range Features {
		b.WriteString("| " + f + " |")
		for i := range entries {
			c, ok := entries[i].Features[f]
			b.WriteString(" " + symbol(c, ok) + " |")
		}
		b.WriteString("\n")
	}
	b.WriteString("\n" + Legend)
	return b.String()
}

// renderCoverage is what the matrix could not say before: which of the specification's
// claims this evidence actually covers.
//
// docs/status.md's M2 exit says eleven capability claims have no behavioural
// probe, so a driver that claimed one could not be held to it. That list was
// written by hand and is now derived from the evidence, which is the only way
// it stays true. The "probed by some runs and not others" section is the one
// nobody had noticed: the corpus mixes reports from nine different commits, so
// a feature whose probe arrived in one of them is measured for the drivers
// that ran afterwards and unmeasured for the rest -- and the matrix rendered
// the difference as a capability difference.
func renderCoverage(entries []entry) string {
	counts := map[string]int{}
	probedBy := map[string][]string{}
	unprobedBy := map[string][]string{}
	for i := range entries {
		e := &entries[i]
		for _, f := range Features {
			c, ok := e.Features[f]
			if !ok {
				continue
			}
			counts[c.State]++
			if c.Probed {
				probedBy[f] = append(probedBy[f], e.name(" (", ")"))
			} else {
				unprobedBy[f] = append(unprobedBy[f], e.name(" (", ")"))
			}
		}
	}
	var b strings.Builder
	b.WriteString("## What this evidence covers\n\n")
	b.WriteString("| Claims | State |\n|---:|---|\n")
	for _, s := range []struct {
		state report.State
		what  string
	}{
		{report.StateVerified, "verified: advertised, and a probe proved it in both directions"},
		{report.StateRefuted, "refuted: not offered, and a probe observed the refusal"},
		{report.StateAdvertised, "**advertised only**: the driver claims it and no probe verified it"},
		{report.StateUnverified, "unverified: not offered, and nothing established that either"},
		{report.StateUnrefuted, "unrefuted: a denied guarantee no run contradicted "},
		{report.StateUnread, "unread: no scenario reached a client, so the run never read the driver's level"},
		{report.StateFailed, "failed: a scenario for the claim did not pass"},
	} {
		fmt.Fprintf(&b, "| %d | %s |\n", counts[string(s.state)], s.what)
	}
	var none, some []string
	for _, f := range Features {
		switch {
		case len(probedBy[f]) == 0 && len(unprobedBy[f]) > 0:
			none = append(none, f)
		case len(probedBy[f]) > 0 && len(unprobedBy[f]) > 0:
			some = append(some, f)
		}
	}
	fmt.Fprintf(&b, "\n### No behavioural probe in any run (%d)\n\n", len(none))
	if len(none) == 0 {
		b.WriteString("_None: every capability has a probe._\n")
	} else {
		b.WriteString("A driver that advertises one of these cannot be held to it, so its cell reads `(N)` and not `N`. The kit has no scenario that exercises them:\n\n")
		for _, f := range none {
			b.WriteString("- `" + f + "`\n")
		}
	}
	fmt.Fprintf(&b, "\n### Probed by some runs and not others (%d)\n\n", len(some))
	if len(some) == 0 {
		b.WriteString("_None: every capability is probed by every run or by none._\n")
	} else {
		b.WriteString("These rows are not comparable across columns. A cell with no evidence is not a capability difference — it is a run that produced none, and there are three reasons a run can do that:\n\n")
		b.WriteString("- the kit had no probe for the claim at the commit that ran it. `Receipts` is probed by the two Pulsar runs alone because their reports come from the commit that added the probe and the other twenty predate it — which the old matrix rendered as Pulsar having receipts and nobody else having them;\n")
		b.WriteString("- the driver documented the scenario as inapplicable (`Harness.Skip`);\n")
		b.WriteString("- the driver refused the topology the probe needed.\n\n")
		b.WriteString("Which of the three it was is on the driver's own page, in the `Why` column.\n\n")
		b.WriteString("| Capability | Runs with evidence | Runs with none |\n|---|---:|---|\n")
		for _, f := range some {
			fmt.Fprintf(&b, "| `%s` | %d of %d | %s |\n", f, len(probedBy[f]), len(probedBy[f])+len(unprobedBy[f]), strings.Join(unprobedBy[f], ", "))
		}
	}
	return b.String()
}

// renderProvenance is the table that makes the matrix a claim about software
// versions rather than about names. Nothing tied a report to what produced it
// before: the version was in the JSON and in no generated artefact.
func renderProvenance(entries []entry) string {
	var b strings.Builder
	b.WriteString("## Provenance\n\n")
	b.WriteString("Every column above, and the run that produced it. `confgen` refuses a report whose commit is not a commit, whose broker image `conformance/harness/images.lock` does not pin, that no suite of `conformance/suites.json` publishes, that ran in the future, or that is further behind the newest report here than its `-max-stale` allows.\n\n")
	b.WriteString("| Driver | Evidence | Broker image | Client | Go | Commit | Ran at |\n|---|---|---|---|---|---|---|\n")
	for i := range entries {
		e := &entries[i]
		client := "`" + e.Client.Module + "`"
		if e.Client.Version != "" {
			client += " " + e.Client.Version
		}
		fmt.Fprintf(&b, "| %s | %s | `%s` | %s | %s | `%s` | %s |\n",
			e.name(" (", ")"), e.Evidence, e.Broker.Image, client, e.Go, e.sourceRevision(), e.Date)
	}
	commits := map[string]bool{}
	for i := range entries {
		if entries[i].Commit != "" {
			commits[entries[i].Commit] = true
		}
	}
	if len(commits) > 1 {
		fmt.Fprintf(&b, "\n%d different commits produced this matrix. A row whose probe arrived between two of them is marked above under \"probed by some runs and not others\"; the nightly `aggregate` job refreshes every column from one tree.\n", len(commits))
	}
	return b.String()
}

func (e *entry) sourceRevision() string {
	if e.Commit != "" {
		return e.Commit
	}
	if e.CommitStatus != "" {
		return e.CommitStatus
	}
	return "unrecorded"
}

func renderDriver(e *entry) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s from %s (%s, %s, commit %s) -->\n\n", GeneratedMarker, e.Date, e.Broker.Image, e.Evidence, e.sourceRevision())
	b.WriteString("| Capability | Level | Evidence | Why |\n|---|---|---|---|\n")
	for _, f := range Features {
		c, ok := e.Features[f]
		if !ok {
			continue
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", f, c.Level, evidenceOf(c), why(c))
	}
	return b.String()
}

// evidenceOf renders the claim's state as the answer to "is this verified?",
// which used to be the word "false" for four different reasons.
func evidenceOf(c claim) string {
	switch report.State(c.State) {
	case report.StateVerified:
		return "verified by a probe"
	case report.StateRefuted:
		return "refusal observed"
	case report.StateUnrefuted:
		return "unrefuted"
	case report.StateAdvertised:
		return "**advertised only**"
	case report.StateUnread:
		return "level not read"
	case report.StateFailed:
		return "**a scenario FAILED**"
	default:
		return "unverified"
	}
}

// why is the run's own reason, which is the thing the driver pages promised
// and could not deliver: a skip written before the kit had a client carried no
// feature, so its reason was filed against no claim at all.
func why(c claim) string {
	switch report.State(c.State) {
	case report.StateVerified, report.StateRefuted:
		return ""
	case report.StateUnrefuted:
		return "a guarantee's absence is not observable in one run "
	case report.StateFailed, report.StateAdvertised, report.StateUnverified, report.StateUnread:
		if c.Why == "" {
			return "no reason recorded"
		}
		// A reason with a pipe in it would split the row it is a cell
		// of, which is the trap the contributor notes records for the ADR
		// ledger, met here from the generated side.
		return strings.ReplaceAll(strings.ReplaceAll(c.Why, "|", "\\|"), "\n", " ")
	default:
		return "no reason recorded"
	}
}

// ---------------------------------------------------------------- the outputs

func render(entries []entry, root string) (map[string][]byte, error) {
	outputs := map[string][]byte{}
	capJSON, err := json.MarshalIndent(map[string]any{"schema": report.Schema, "drivers": entries}, "", "  ")
	if err != nil {
		return nil, err
	}
	outputs[filepath.Join(root, "capabilities.json")] = append(capJSON, '\n')
	matrix := renderMatrix(entries)
	var b strings.Builder
	b.WriteString("# Capability matrix\n\nGenerated by `conformance/cmd/confgen` from the conformance reports in `conformance/reports/latest`. A capability renders as support only where a probe verified it in BOTH directions; a level in parentheses is a claim the driver advertises and nothing checked.\n\n<!-- matrix:start -->\n")
	b.WriteString(matrix)
	b.WriteString("<!-- matrix:end -->\n\n")
	b.WriteString(renderCoverage(entries))
	b.WriteString("\n")
	b.WriteString(renderProvenance(entries))
	outputs[filepath.Join(root, "docs", "drivers", "matrix.md")] = []byte(b.String())
	for i := range entries {
		e := &entries[i]
		outputs[filepath.Join(root, "docs", "drivers", e.name("-", "")+".capabilities.md")] = []byte(renderDriver(e))
	}
	readme := filepath.Join(root, "README.md")
	data, err := os.ReadFile(readme)
	if err != nil {
		return nil, fmt.Errorf("the README carries the generated matrix block and cannot be read: %w", err)
	}
	updated, ok := replaceBlock(string(data), "matrix", matrix)
	if !ok {
		return nil, fmt.Errorf("%s has no <!-- matrix:start --> … <!-- matrix:end --> block, so the generated matrix it publishes is not generated by anything", readme)
	}
	outputs[readme] = []byte(updated)
	return outputs, nil
}

// reconcile writes or checks every output, and deals with an artefact this
// command no longer writes.
//
// The second half is the gap `-check` had: every file confgen WRITES is
// compared, so a page nobody regenerates is compared with nothing. Remove a
// driver's report and its `docs/drivers/<driver>.capabilities.md` stays on
// disk, stating capabilities from evidence that is gone, and `confgen -check`
// exits 0.
func reconcile(outputs map[string][]byte, opt options) ([]string, error) {
	var drift []string
	for path, content := range outputs {
		if opt.check {
			cur, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(cur, content) {
				drift = append(drift, path)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return nil, err
		}
		if err := os.WriteFile(path, content, 0o644); err != nil {
			return nil, err
		}
	}
	pages, err := filepath.Glob(filepath.Join(opt.root, "docs", "drivers", "*.capabilities.md"))
	if err != nil {
		return nil, err
	}
	for _, page := range pages {
		if _, ok := outputs[page]; ok {
			continue
		}
		data, err := os.ReadFile(page)
		if err != nil {
			return nil, err
		}
		if !bytes.HasPrefix(data, []byte(GeneratedMarker)) {
			// Somebody's hand-written page, which this command has
			// no business deleting.
			continue
		}
		if opt.check {
			drift = append(drift, page+" (no report produces it)")
			continue
		}
		if err := os.Remove(page); err != nil {
			return nil, err
		}
		fmt.Fprintf(os.Stderr, "confgen: removed %s: no report produces it any more\n", page)
	}
	return drift, nil
}

// replaceBlock replaces the content between <!-- name:start --> and
// <!-- name:end --> markers.
func replaceBlock(doc, name, content string) (string, bool) {
	start := "<!-- " + name + ":start -->"
	end := "<!-- " + name + ":end -->"
	i := strings.Index(doc, start)
	j := strings.Index(doc, end)
	if i < 0 || j < 0 || j < i {
		return doc, false
	}
	return doc[:i+len(start)] + "\n" + content + doc[j:], true
}
