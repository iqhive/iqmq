#!/usr/bin/env bash
# Resolve every image in the conformance harness to its digest and write
# conformance/harness/images.lock (name image@sha256:...). Images already
# present locally are not re-pulled (PULL=1 forces a pull), so an expired
# registry credential helper does not block the lock.
#
# The digest recorded is the repo digest whose REPOSITORY is the one images.go
# names -- NOT `RepoDigests[0]`. An image known under two repository names has
# two repo digests and the first can be the other name: on the host where this
# was found, the quay.io-pinned MinIO image's first repo digest is the dead
# Docker Hub name `minio/minio@...`, so a regeneration wrote a reference nobody
# can pull. When no repo digest names the declared
# repository this script FAILS and names the image; it never falls back to an
# arbitrary entry, because a lock full of plausible-looking wrong digests pins
# the wrong thing while every gate stays green.
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
lock="$root/conformance/harness/images.lock"

# repository_of prints the repository part of an image reference: the digest and
# then the tag are dropped, where the tag's colon is the last one AFTER the last
# slash so a registry port is not read as a tag. Both sides of the comparison
# below go through it, so `minio/minio` never matches `quay.io/minio/minio` the
# way a prefix or substring test would.
repository_of() {
  local ref="${1%%@*}"
  if [[ "${ref##*/}" == *:* ]]; then
    ref="${ref%:*}"
  fi
  printf '%s' "$ref"
}

# repo_digest_for prints the `repository@sha256:...` docker reports for image $1
# whose repository is exactly $2, and fails when there is none.
repo_digest_for() {
  local image="$1" want="$2" rd
  while read -r rd; do
    [ -n "$rd" ] || continue
    if [ "$(repository_of "$rd")" = "$want" ]; then
      printf '%s' "$rd"
      return 0
    fi
  done < <(docker image inspect --format '{{range .RepoDigests}}{{println .}}{{end}}' "$image")
  return 1
}

entries=()
mapfile -t entries < <(grep -oE '^\s+"[a-z0-9-]+":\s+"[^"]+"' "$root/conformance/harness/images.go" | sed -E 's/^\s+"([a-z0-9-]+)":\s+"([^"]+)"/\1 \2/')
if [ "${#entries[@]}" -eq 0 ]; then
  echo "images-lock: conformance/harness/images.go has no \"name\": \"image\" line; that one-entry-per-line formatting is what this script parses" >&2
  exit 1
fi

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
echo "# Generated by hack/images-lock.sh on $(date -u +%F). name image@digest" > "$tmp"
for entry in "${entries[@]}"; do
  read -r name image <<<"$entry"
  if [ "${PULL:-0}" = 1 ] || ! docker image inspect "$image" >/dev/null 2>&1; then
    docker pull -q "$image" >/dev/null
  fi
  want="$(repository_of "$image")"
  if ! digest="$(repo_digest_for "$image" "$want")"; then
    echo "images-lock: $name ($image): no repo digest names repository $want; docker reports $(docker image inspect --format '{{json .RepoDigests}}' "$image")" >&2
    echo "images-lock: refusing to lock a repository conformance/harness/images.go does not name" >&2
    exit 1
  fi
  echo "$name $digest" >> "$tmp"
  echo "  $name -> $digest"
done
mv "$tmp" "$lock"
echo "wrote $lock"
